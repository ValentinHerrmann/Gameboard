function loadImages() {
    const contentDiv = document.getElementById('content');

    for (const [folder, files] of Object.entries(resources)) {
        const folderDiv = document.createElement('div');
        folderDiv.classList.add('folder');

        const folderTitle = document.createElement('h2');
        folderTitle.classList.add('collapsible-header');

        const toggleIcon = document.createElement('span');
        toggleIcon.textContent = '▶'; // Default collapsed state
        toggleIcon.style.marginRight = '10px'; // Add spacing between the icon and the text
        folderTitle.appendChild(toggleIcon);

        const folderText = document.createTextNode(folder);
        folderTitle.appendChild(folderText);

        folderTitle.addEventListener('click', () => {
            const grid = folderDiv.querySelector('.image-grid');
            grid.classList.toggle('hidden'); // Toggles visibility
            toggleIcon.textContent = grid.classList.contains('hidden') ? '▶' : '▼';
        });

        folderDiv.appendChild(folderTitle);

        const imageGrid = document.createElement('div');
        imageGrid.classList.add('image-grid', 'hidden'); // Initially hidden

        files.forEach(file => {
            const imageItem = document.createElement('div');
            imageItem.classList.add('image-item');

            const filePath = document.createElement('p');
            filePath.textContent = file;
            imageItem.appendChild(filePath);

            const link = document.createElement('a');
            link.href = file;
            link.target = '_blank';

            const img = document.createElement('img');
            img.src = file;
            img.alt = file;

            link.appendChild(img);
            imageItem.appendChild(link);
            imageGrid.appendChild(imageItem);
        });

        folderDiv.appendChild(imageGrid);
        contentDiv.appendChild(folderDiv);
    }
}

